"""Resolve exact release pins; run in a clean virtual environment before reviewing upgrades."""

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def resolve(requirements):
    with tempfile.TemporaryDirectory(prefix="receipt-resolution-") as directory:
        report = Path(directory) / "report.json"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "pip",
                "install",
                "--dry-run",
                "--ignore-installed",
                "-r",
                str(ROOT / requirements),
                "--report",
                str(report),
            ],
            check=True,
        )
        rows = json.loads(report.read_text())["install"]
        return {
            row["metadata"]["name"].lower().replace("_", "-"): row["metadata"][
                "version"
            ]
            for row in rows
        }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="Replace reviewed pin files after resolution",
    )
    args = parser.parse_args()
    runtime = resolve("requirements.txt")
    development = resolve("requirements-dev.txt")
    incompatible = {name for name in runtime if development.get(name) != runtime[name]}
    if incompatible:
        raise SystemExit(
            "Runtime and development resolutions disagree; review constraints: "
            + ", ".join(sorted(incompatible))
        )
    header = "# Exact release dependencies; generated by python tools/lock_dependencies.py --write.\n# Python 3.11-3.14 on supported Mac/Linux platforms are checked in CI.\n"
    files = {
        "requirements.lock": header
        + "".join(f"{name}=={version}\n" for name, version in sorted(runtime.items())),
        "requirements-dev.lock": header
        + "-r requirements.lock\n"
        + "".join(
            f"{name}=={version}\n"
            for name, version in sorted(development.items())
            if name not in runtime
        ),
    }
    if args.write:
        for name, content in files.items():
            (ROOT / name).write_text(content)
    else:
        for name, content in files.items():
            print(name + "\n" + content)


if __name__ == "__main__":
    main()
